                    .fsType = table.fsType,
                    .ySubscriptXSize = table.ySubscriptXSize,
                    .ySubscriptYSize = table.ySubscriptYSize,
                    .ySubscriptXOffset = table.ySubscriptXOffset,
                    .ySubscriptYOffset = table.ySubscriptYOffset,
